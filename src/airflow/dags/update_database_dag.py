"""
Airflow DAG for laptop web crawling and Neo4j import
Updated to match the new Neo4j schema with Laptop nodes and proper relationships
"""
import os
import sys
import logging
from datetime import datetime, timedelta

from airflow import DAG
from airflow.operators.python import PythonOperator
from airflow.providers.neo4j.operators.neo4j import Neo4jOperator
from airflow.providers.neo4j.hooks.neo4j import Neo4jHook

# Import the crawler module
from crawler.web_crawler import TGDD_Crawler

# Import the data processor module
from data_processor import Neo4jDataProcessor

# Neo4j connection details
NEO4J_CONN_ID = 'neo4j_default'
NEO4J_HOST = os.getenv('NEO4J_HOST')
NEO4J_PORT = os.getenv('NEO4J_PORT')
NEO4J_USER = os.getenv('NEO4J_USER')
NEO4J_PASSWORD = os.getenv('NEO4J_PASSWORD')

# Define default arguments for the DAG
default_args = {
    'owner': 'phukhanh',
    'depends_on_past': False,
    'email_on_failure': False,
    'email_on_retry': False,
    'retries': 1,
    'retry_delay': timedelta(minutes=5),
    'start_date': datetime(2023, 8, 1),
}

def run_crawler(**context):
    # Use Python logging instead of task instance log
    logger = logging.getLogger(__name__)
    
    try:
        # Pass the logger to the crawler
        crawler = TGDD_Crawler(logger=logger)
        saved_file = crawler.run()
        
        if saved_file:
            # Push the file path to XCom for downstream tasks
            context['ti'].xcom_push(key='saved_file_path', value=saved_file)
            logger.info(f"Crawler run successful. Saved file: {saved_file}")
            return saved_file
        else:
            logger.error("Crawler did not save any file.")
            raise ValueError("Crawler did not save any file")
            
    except Exception as e:
        logger.error(f"Error running crawler: {str(e)}", exc_info=True)
        raise


def prepare_neo4j_import(**context):
    """Prepare data for Neo4j import using the Neo4jDataProcessor module"""
    logger = logging.getLogger(__name__)
    
    # Get the saved file path from the crawler task
    saved_file = context['ti'].xcom_pull(task_ids='crawl_laptop_data', key='saved_file_path')
    
    if not saved_file:
        raise ValueError("No saved file path received from crawler task")
    
    try:
        # Initialize the data processor with logger
        processor = Neo4jDataProcessor(logger=logger)
        
        # Process the data file and generate Cypher queries
        import_file = processor.process_data_file(saved_file)
        
        # Push import file path to XCom
        context['ti'].xcom_push(key='import_file_path', value=import_file)
        return import_file
        
    except Exception as e:
        logger.error(f"Failed to prepare Neo4j import using data processor: {str(e)}", exc_info=True)
        raise

def execute_cypher_import(**context):
    """Execute the generated Cypher import file"""
    logger = logging.getLogger(__name__)
    
    try:
        # Get import file path from previous task
        import_file = context['ti'].xcom_pull(task_ids='prepare_neo4j_import', key='import_file_path')
        
        if not import_file:
            raise ValueError("No import file path received from previous task")
            
        if not os.path.exists(import_file):
            raise ValueError(f"Import file not found: {import_file}")
        
        # Read and validate Cypher queries
        with open(import_file, 'r', encoding='utf-8') as f:
            cypher_script = f.read().strip()
        
        if not cypher_script:
            logger.warning("No Cypher queries to execute - empty file")
            return "No data to import"
        
        # Execute via Neo4j hook with error handling
        hook = Neo4jHook(conn_id=NEO4J_CONN_ID)
        
        # Split script into individual queries - each query starts with MERGE, MATCH, CREATE, etc.
        queries = []
        
        for line in cypher_script.split('\n'):
            line = line.strip()
            if not line or line.startswith('//'):  # Skip empty lines and comments
                continue
            
            # Each line in the file generated by Neo4jDataProcessor is a complete query
            # No need to combine multiple lines - just add each non-empty line as a query
            queries.append(line)
        
        successful_queries = 0
        failed_queries = 0
        error_details = []
        
        logger.info(f"Starting to execute {len(queries)} Cypher queries...")
        
        for i, query in enumerate(queries):
            try:
                if query:  # Only execute non-empty queries
                    hook.run(query)
                    successful_queries += 1
                    if (i + 1) % 100 == 0:  # Log progress every 100 queries
                        logger.info(f"Progress: {i + 1}/{len(queries)} queries executed")
            except Exception as query_error:
                failed_queries += 1
                error_msg = str(query_error)
                error_details.append({
                    'query_number': i + 1,
                    'error': error_msg,
                    'query_preview': query[:300] + '...' if len(query) > 300 else query
                })
                
                # Log first few errors in detail
                if failed_queries <= 5:
                    logger.error(f"Query {i+1} failed: {error_msg}")
                    logger.error(f"Query: {query}")
                elif failed_queries == 6:
                    logger.error("Too many errors - suppressing detailed error logs...")
        
        logger.info(f"Cypher import completed: {successful_queries} successful, {failed_queries} failed")
        
        # Log error summary
        if error_details:
            error_types = {}
            for error in error_details:
                error_type = error['error'].split(':')[0] if ':' in error['error'] else error['error']
                error_types[error_type] = error_types.get(error_type, 0) + 1
            
            logger.error("Error summary:")
            for error_type, count in error_types.items():
                logger.error(f"  {error_type}: {count} occurrences")
        
        # More lenient failure threshold - allow up to 50% failures for initial import
        failure_rate = failed_queries / len(queries) if queries else 0
        if failure_rate > 0.5:
            raise ValueError(f"Too many failed queries: {failed_queries} failed out of {len(queries)} total ({failure_rate:.1%} failure rate)")
        
        return f"Import completed: {successful_queries} queries executed successfully"
        
    except Exception as e:
        logger.error(f"Error in Cypher import: {str(e)}", exc_info=True)
        raise

# Create the DAG
with DAG(
    'update_database_dag',
    default_args=default_args,
    description='Web crawler for laptop data with Neo4j import using new Laptop schema',
    schedule='0 7 * * 1',  # Weekly on Monday at 7 AM
    catchup=False,
    tags=['crawler', 'laptop', 'neo4j', 'schema-v2'],
    max_active_runs=1,  # Prevent concurrent runs
) as dag:
        
    crawl_task = PythonOperator(
        task_id='crawl_laptop_data',
        python_callable=run_crawler,
        dag=dag,
    )
    
    
    prepare_import_task = PythonOperator(
        task_id='prepare_neo4j_import',
        python_callable=prepare_neo4j_import,
        dag=dag,
    )
    
    
    # Clear existing laptop data before import (full replacement strategy)
    clear_data_task = Neo4jOperator(
        task_id='clear_old_data',
        neo4j_conn_id=NEO4J_CONN_ID,
        sql="""
        // Clear all existing laptop data for full replacement
        MATCH (n)
        DETACH DELETE n
        """,
        dag=dag,
    )
    
    # Import data to Neo4j using dynamic Cypher execution
    import_data_task = PythonOperator(
        task_id='import_to_neo4j',
        python_callable=execute_cypher_import,
        dag=dag,
    )

    # Set task dependencies
    crawl_task >>  prepare_import_task >>  clear_data_task >> import_data_task